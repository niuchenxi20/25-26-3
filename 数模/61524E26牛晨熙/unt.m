% 物价指数预测
m = [1:26]';                      % 时间序号 1~26
CPI = [100,101.7,106.1,108.7,109.8,111.1,113.2,109.8,111,113.2,...
       115.2,116.9,119.9,121.9,124.3,134.4,137.2,138.5,139.4,140.5,...
       142.3,143.6,144.2,146,147.9,149.6]';

% 用最近8个月做线性回归
